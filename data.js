/** Präfix für Archivsignaturen, z. B. AK-1989-014 */
const ARCHIV_PREFIX = 'AK';

/** Zweisprachiger Katalogeintrag; interne Logik nutzt `.de`. */
function L(de, en) {
  return { de: de, en: en };
}

function isLocalizedEntry(item) {
  return !!(item && typeof item === 'object' && typeof item.de === 'string');
}

function textDe(item) {
  if (item == null) {
    return item;
  }
  return isLocalizedEntry(item) ? item.de : item;
}

function textEn(item) {
  if (item == null) {
    return item;
  }
  return isLocalizedEntry(item) ? (item.en || item.de) : item;
}

